"""Generate the monochrome boot bitmap from approved banner (Pillow)."""
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parents[1]
im = Image.open(root / 'assets/branding/boot-source.png').convert('L').resize((304, 102), Image.Resampling.LANCZOS)
im = im.point(lambda v: 255 if v >= 110 else 0).convert('1')
im.save(root / 'assets/branding/boot-preview.png')
data = im.tobytes()
out = root / '.integration/openfpgaos/src/firmware/os/targets/pocket/chiskit_splash.h'
out.write_text('/* Generated by tests/generate-boot-splash.py; 304x102 MSB-first. */\nstatic const unsigned char chiskit_splash[] = {\n' + '\n'.join(','.join(f'0x{v:02x}' for v in data[i:i+24])+',' for i in range(0,len(data),24)) + '\n};\n', encoding='ascii')
assert len(data) == 3876
print('PASS: 304x102, 3876 bytes')
